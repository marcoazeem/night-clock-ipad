"""Writes Config.h from lights.json (the same file the Flutter build uses).

Every key becomes a C string #define; FORCE_* preview switches come from
the environment (FORCE_NIGHT=1 ./ipad/build.sh). Usage:
  python3 make_config.py lights.json build/Config.h
"""

import json
import os
import sys

src, out = sys.argv[1], sys.argv[2]
cfg = json.load(open(src)) if os.path.exists(src) else {}
keys = ['TAPO_HASH', 'TAPO_LIGHTS', 'MI_LIGHTS', 'DIMMABLE_LIGHTS', 'GREE_AC',
        'HISENSE_TV', 'WEATHER_AT', 'BEYOND_TV', 'ROOMS', 'START_ROOM', 'ROOM_PINS', 'SONOFF_SWITCHES',
        'BILLS', 'AC_BTU', 'BILL_DAY', 'ENERGY_BASELINE_W']
lines = ['// Generated by ipad/tool/make_config.py — do not edit, do not commit.']
for k in sorted(set(keys) | set(cfg)):
    v = str(cfg.get(k, ''))
    # The iPad sits in its own room: build.sh passes START_ROOM.
    if k == 'START_ROOM' and os.environ.get('START_ROOM'):
        v = os.environ['START_ROOM']
    v = v.replace('\\', '\\\\').replace('"', '\\"')
    lines.append(f'#define {k} "{v}"')
for k in ['FORCE_NIGHT', 'FORCE_MORNING', 'FORCE_RAIN', 'FORCE_CLEAR']:
    on = os.environ.get(k, '') in ('1', 'true', 'yes')
    lines.append(f'#define {k} {1 if on else 0}')
open(out, 'w').write('\n'.join(lines) + '\n')
